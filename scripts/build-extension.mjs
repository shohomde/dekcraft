import {build} from 'esbuild';
import {mkdir,cp,writeFile,readFile,rm} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
const output='release/dekcraft-extension';
await rm(output,{recursive:true,force:true});await mkdir(output,{recursive:true});
for(const name of ['manifest.json','options.html','offscreen.html','content.css'])await cp('extension/'+name,output+'/'+name);
await cp('extension/icons',output+'/icons',{recursive:true});
await cp('public/fonts',output+'/fonts',{recursive:true});
await writeFile(output+'/options.css',(await readFile('app/globals.css','utf8')).replaceAll('../fonts/','fonts/'));
await cp('LICENSE',output+'/LICENSE');
await cp('INSTALL.txt',output+'/INSTALL.txt');
await cp('THIRD_PARTY_NOTICES.txt',output+'/THIRD_PARTY_NOTICES.txt');
await build({entryPoints:['extension/content.ts','extension/background.ts','extension/offscreen.ts'],outdir:output,bundle:true,format:'iife',target:'chrome120',minify:true});
await build({entryPoints:['extension/options.tsx'],outfile:output+'/options.js',bundle:true,format:'iife',jsx:'automatic',target:'chrome120',minify:true,define:{'process.env.NODE_ENV':'"production"'}});
await build({entryPoints:['extension/semantic-worker.ts'],outfile:'public/semantic/worker.js',bundle:true,format:'esm',platform:'browser',target:'chrome120',minify:true});
await cp('public/semantic',output+'/semantic',{recursive:true});
await mkdir('public/downloads',{recursive:true});
await rm('public/downloads/dekcraft-extension.zip',{force:true});
execFileSync('zip',['-qr','../public/downloads/dekcraft-extension.zip','dekcraft-extension'],{cwd:'release'});
console.log('Built installable extension in '+output);
